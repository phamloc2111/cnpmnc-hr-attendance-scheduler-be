package com.company.hr.attendance.attendance.application;

import com.company.hr.attendance.attendance.api.AttendanceModels.TimemarkAnalysisResponse;
import com.fasterxml.jackson.core.JsonProcessingException;
import com.fasterxml.jackson.databind.JsonNode;
import com.fasterxml.jackson.databind.ObjectMapper;
import java.io.IOException;
import java.util.Base64;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.beans.factory.annotation.Value;
import org.springframework.http.HttpStatus;
import org.springframework.http.MediaType;
import org.springframework.http.client.SimpleClientHttpRequestFactory;
import org.springframework.stereotype.Service;
import org.springframework.util.StringUtils;
import org.springframework.web.client.ResourceAccessException;
import org.springframework.web.client.RestClient;
import org.springframework.web.client.RestClientException;
import org.springframework.web.client.RestClientResponseException;
import org.springframework.web.multipart.MultipartFile;

/** Gemini-backed OCR for the text overlay generated by the Timemark mobile app. */
@Service
public class TimemarkReader {
    private static final long MAX_IMAGE_BYTES = 5L * 1024 * 1024;
    private static final List<String> ACCEPTED_MIME_TYPES = List.of("image/jpeg", "image/png", "image/webp");
    private final ObjectMapper json;
    private final RestClient client;
    private final String apiKey;
    private final String model;

    @Autowired
    public TimemarkReader(
        ObjectMapper json,
        @Value("${app.ai.gemini.api-key:}") String apiKey,
        @Value("${app.ai.gemini.model:gemini-2.5-flash-lite}") String model,
        @Value("${app.ai.gemini.timeout-ms:4000}") int timeoutMs
    ) {
        var factory = new SimpleClientHttpRequestFactory();
        factory.setConnectTimeout(Math.min(timeoutMs, 1_000));
        factory.setReadTimeout(timeoutMs);
        var client = RestClient.builder()
            .baseUrl("https://generativelanguage.googleapis.com/v1beta/models")
            .requestFactory(factory)
            .build();
        this.json = json;
        this.apiKey = apiKey;
        this.model = model;
        this.client = client;
    }

    TimemarkReader(ObjectMapper json, String apiKey, String model, RestClient client) {
        this.json = json;
        this.apiKey = apiKey;
        this.model = model;
        this.client = client;
    }

    public TimemarkAnalysisResponse read(MultipartFile image) {
        validate(image);
        if (!StringUtils.hasText(apiKey)) {
            throw new AttendanceException(HttpStatus.SERVICE_UNAVAILABLE, "TIMEMARK_AI_NOT_CONFIGURED",
                "Dịch vụ đọc ảnh Timemark chưa được cấu hình. Vui lòng liên hệ quản trị viên.");
        }
        String rawResponse;
        try {
            rawResponse = client.post()
                .uri("/{model}:generateContent", model)
                .header("x-goog-api-key", apiKey)
                .accept(MediaType.APPLICATION_JSON)
                .contentType(MediaType.APPLICATION_JSON)
                .body(request(image))
                .retrieve()
                .body(String.class);
        } catch (AttendanceException error) {
            throw error;
        } catch (ResourceAccessException error) {
            throw new AttendanceException(HttpStatus.SERVICE_UNAVAILABLE, "TIMEMARK_AI_UNAVAILABLE",
                "Không thể đọc ảnh Timemark trong thời gian cho phép. Vui lòng thử lại hoặc gửi giải trình.");
        } catch (RestClientResponseException error) {
            throw upstreamFailure(error);
        } catch (RestClientException error) {
            throw new AttendanceException(HttpStatus.BAD_GATEWAY, "TIMEMARK_AI_FAILED",
                "Không thể nhận phản hồi từ Google AI. Vui lòng thử lại hoặc gửi giải trình.");
        }
        JsonNode response;
        try {
            response = json.readTree(rawResponse);
        } catch (JsonProcessingException | IllegalArgumentException error) {
            throw new AttendanceException(HttpStatus.BAD_GATEWAY, "TIMEMARK_AI_RESPONSE_INVALID",
                "Phản hồi HTTP của Google AI không phải JSON hợp lệ. Vui lòng thử lại hoặc gửi giải trình.");
        }
        try {
            return toResult(response);
        } catch (JsonProcessingException error) {
            throw new AttendanceException(HttpStatus.BAD_GATEWAY, "TIMEMARK_AI_OUTPUT_INVALID",
                "Kết quả đọc ảnh của Google AI không đúng định dạng. Vui lòng thử lại hoặc gửi giải trình.");
        }
    }

    private AttendanceException upstreamFailure(RestClientResponseException error) {
        int status = error.getStatusCode().value();
        if (status == 400) {
            var googleError = googleError(error);
            if ("API_KEY_INVALID".equals(googleError.reason())) {
                return new AttendanceException(HttpStatus.SERVICE_UNAVAILABLE, "TIMEMARK_AI_AUTH_FAILED",
                    "GEMINI_API_KEY không được Google AI chấp nhận. Vui lòng liên hệ quản trị viên kiểm tra API key.");
            }
            if ("FAILED_PRECONDITION".equals(googleError.status())) {
                return new AttendanceException(HttpStatus.SERVICE_UNAVAILABLE, "TIMEMARK_AI_PRECONDITION_FAILED",
                    "Google AI chưa cho phép dự án sử dụng dịch vụ. Vui lòng kiểm tra billing và khu vực trong Google AI Studio.");
            }
            if ("INVALID_ARGUMENT".equals(googleError.status())) {
                var field = googleError.field().isEmpty() ? "" : " Trường bị từ chối: " + googleError.field() + ".";
                return new AttendanceException(HttpStatus.BAD_GATEWAY, "TIMEMARK_AI_REQUEST_REJECTED",
                    "Google AI từ chối tham số yêu cầu (400 INVALID_ARGUMENT)." + field
                        + " Vui lòng liên hệ quản trị viên kiểm tra cấu hình AI.");
            }
        }
        return switch (status) {
            case 400 -> new AttendanceException(HttpStatus.BAD_GATEWAY, "TIMEMARK_AI_REQUEST_REJECTED",
                "Google AI từ chối yêu cầu đọc ảnh (400). Vui lòng liên hệ quản trị viên kiểm tra cấu hình AI.");
            case 401, 403 -> new AttendanceException(HttpStatus.SERVICE_UNAVAILABLE, "TIMEMARK_AI_AUTH_FAILED",
                "Google AI từ chối quyền truy cập. Vui lòng liên hệ quản trị viên kiểm tra GEMINI_API_KEY.");
            case 404 -> new AttendanceException(HttpStatus.SERVICE_UNAVAILABLE, "TIMEMARK_AI_MODEL_UNAVAILABLE",
                "Không tìm thấy model Google AI đã cấu hình. Vui lòng liên hệ quản trị viên kiểm tra GEMINI_MODEL.");
            case 429 -> new AttendanceException(HttpStatus.SERVICE_UNAVAILABLE, "TIMEMARK_AI_QUOTA_EXCEEDED",
                "Google AI đã hết hạn mức tạm thời. Vui lòng thử lại sau hoặc gửi giải trình.");
            default -> new AttendanceException(HttpStatus.BAD_GATEWAY, "TIMEMARK_AI_FAILED",
                "Google AI không thể xử lý yêu cầu (HTTP " + status + "). Vui lòng thử lại hoặc gửi giải trình.");
        };
    }

    private GoogleError googleError(RestClientResponseException error) {
        try {
            var body = json.readTree(error.getResponseBodyAsByteArray()).path("error");
            var status = body.path("status").asText("");
            var message = body.path("message").asText("");
            var reason = "";
            for (var detail : body.path("details")) {
                if ("API_KEY_INVALID".equals(detail.path("reason").asText())) {
                    reason = "API_KEY_INVALID";
                    break;
                }
            }
            var field = "";
            for (var candidate : List.of("responseJsonSchema", "responseMimeType", "generationConfig", "inlineData", "mimeType", "contents")) {
                if (message.contains(candidate)) {
                    field = candidate;
                    break;
                }
            }
            return new GoogleError(status, reason, field);
        } catch (IOException | IllegalArgumentException ignored) {
            return new GoogleError("", "", "");
        }
    }

    private record GoogleError(String status, String reason, String field) {}

    private Map<String, Object> request(MultipartFile image) {
        try {
            var inlineData = Map.of("mimeType", image.getContentType(), "data", Base64.getEncoder().encodeToString(image.getBytes()));
            var parts = List.of(
                Map.of("text", "Read only the Timemark overlay in this attendance photo. Return printedDateTime as an ISO-8601 date-time with the +07:00 offset, based only on the complete date and time visibly printed in the image. Extract its location coordinates. Do not infer missing values. If either the complete date/time or latitude/longitude cannot be read clearly, set readable=false and explain the specific missing or unreadable overlay in Vietnamese."),
                Map.of("inlineData", inlineData)
            );
            var schema = new LinkedHashMap<String, Object>();
            schema.put("type", "object");
            schema.put("properties", Map.of(
                "readable", Map.of("type", "boolean"),
                "printedDateTime", Map.of("type", List.of("string", "null"), "format", "date-time", "description", "ISO-8601 time read from image, with +07:00 offset"),
                "latitude", Map.of("type", List.of("number", "null"), "minimum", -90, "maximum", 90),
                "longitude", Map.of("type", List.of("number", "null"), "minimum", -180, "maximum", 180),
                "address", Map.of("type", List.of("string", "null")),
                "reason", Map.of("type", List.of("string", "null"), "description", "Vietnamese explanation if unreadable")
            ));
            schema.put("required", List.of("readable", "printedDateTime", "latitude", "longitude", "address", "reason"));
            schema.put("additionalProperties", false);
            return Map.of("contents", List.of(Map.of("parts", parts)), "generationConfig", Map.of(
                "temperature", 0,
                "responseMimeType", "application/json",
                "responseJsonSchema", schema
            ));
        } catch (IOException error) {
            throw new AttendanceException(HttpStatus.BAD_REQUEST, "TIMEMARK_IMAGE_INVALID",
                "Không thể đọc tệp ảnh. Vui lòng tải lại ảnh Timemark ở định dạng JPG, PNG hoặc WEBP.");
        }
    }

    private TimemarkAnalysisResponse toResult(JsonNode response) throws JsonProcessingException {
        var text = response.path("candidates").path(0).path("content").path("parts").path(0).path("text").asText(null);
        if (!StringUtils.hasText(text)) {
            throw new AttendanceException(HttpStatus.BAD_GATEWAY, "TIMEMARK_AI_FAILED",
                "Dịch vụ đọc ảnh Timemark không trả về kết quả. Vui lòng tải lại ảnh hoặc gửi giải trình.");
        }
        var result = json.readValue(text, TimemarkAnalysisResponse.class);
        boolean hasTime = StringUtils.hasText(result.printedDateTime());
        boolean hasCoordinates = result.latitude() != null && result.longitude() != null;
        if (!result.readable() || !hasTime || !hasCoordinates) {
            var reason = StringUtils.hasText(result.reason()) ? result.reason()
                : (!hasTime ? "Không đọc được thời gian trên ảnh Timemark."
                   : (!hasCoordinates ? "Không đọc được tọa độ (kinh độ/vĩ độ) trên ảnh Timemark."
                      : "Không đọc đủ thời gian và tọa độ trên ảnh. Vui lòng tải lại ảnh Timemark rõ nét hoặc gửi giải trình."));
            return new TimemarkAnalysisResponse(false, result.printedDateTime(), result.latitude(), result.longitude(), result.address(), reason);
        }
        return new TimemarkAnalysisResponse(true, result.printedDateTime(), result.latitude(), result.longitude(), result.address(), null);
    }

    private void validate(MultipartFile image) {
        if (image == null || image.isEmpty()) {
            throw new AttendanceException(HttpStatus.BAD_REQUEST, "TIMEMARK_IMAGE_REQUIRED", "Vui lòng tải lên ảnh Timemark.");
        }
        if (image.getSize() > MAX_IMAGE_BYTES || !ACCEPTED_MIME_TYPES.contains(image.getContentType())) {
            throw new AttendanceException(HttpStatus.BAD_REQUEST, "TIMEMARK_IMAGE_INVALID",
                "Ảnh Timemark phải là JPG, PNG hoặc WEBP và không vượt quá 5 MB.");
        }
    }
}
